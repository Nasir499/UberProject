package com.example.uberprojectauthservice.helpers;

import com.example.uberentityservice.models.Driver;
import org.springframework.security.core.GrantedAuthority;
import org.springframework.security.core.userdetails.UserDetails;

import java.util.Collection;
import java.util.Collections;

public class AuthDriverDetails extends Driver implements UserDetails {

    private String username;
    private String password;

    public AuthDriverDetails(Driver driver) {
        this.username = driver.getEmail() != null ? driver.getEmail() : driver.getLicenseNumber();
        this.password = driver.getPassword();
    }

    @Override
    public Collection<? extends GrantedAuthority> getAuthorities() {
        return Collections.emptyList();
    }

    @Override
    public String getUsername() {
        return this.username;
    }

    @Override
    public String getPassword() {
        return this.password;
    }

    @Override
    public boolean isAccountNonExpired() {
        return true;
    }

    @Override
    public boolean isAccountNonLocked() {
        return true;
    }

    @Override
    public boolean isCredentialsNonExpired() {
        return true;
    }

    @Override
    public boolean isEnabled() {
        return true;
    }
}
